/**
 * Writes agent-form data through the Control Panel's pipeline
 * (preProcess → validate → process), mirroring the CP's EntriesController
 * and GlobalVariablesController minus UI concerns. Saves fire the normal events.
 */
final class ContentWriter
{
    /**
     * Entry attributes Statamic stores next to the fields. A blueprint field with
     * one of these handles would let data overwrite them (`published` decides
     * publication when the file is read back), so the CP never takes them from data.
     */
    private const array ENTRY_ATTRIBUTES = ['id', 'origin', 'published', 'blueprint', 'updated_by', 'updated_at'];

    /**
     * The same for terms (`Term::fileData()`).
     */
    private const array TERM_ATTRIBUTES = ['id', 'blueprint', 'localizations', 'updated_by', 'updated_at'];

    /**
     * @param  array<array-key, mixed>  $data
     */
    public static function createEntry(User $user, Collection $collection, Blueprint $blueprint, Site $site, array $data, ?string $parent): Entry
    {
        $fields = $blueprint->fields();
        self::assertKnown($fields, array_keys($data), self::ENTRY_ATTRIBUTES);

        $stored = AgentForm::toStored($fields, $data, []);
        self::assertReadOnlyUnchanged($fields, $stored, [], self::lockedHandles($collection, $blueprint));

        // The CP makes such editors the author of what they create.
        if (self::authorLocked($collection, $blueprint)) {
            $stored['author'] = [$user->getAuthIdentifier()];
        }

        // The CP's slug field fills itself from the title in the browser.
        if (! isset($stored['slug']) && $blueprint->hasField('slug') && ! $collection->autoGeneratesTitles() && is_string($stored['title'] ?? null)) {
            $stored['slug'] = Str::slug($stored['title'], '-', $site->lang());
        }

        $preProcessed = self::preProcess($fields, $stored);

        self::validate($fields, $stored, $data, fn () => $preProcessed->validator()
            ->withRules(Entries::createRules($collection, $site))
            ->withReplacements(['collection' => $collection->handle(), 'site' => $site->handle()])
            ->validate());

        $values = self::processed($preProcessed, $stored)->except(['slug', 'blueprint', 'published']);

        /** @var Entry $entry */
        $entry = Entries::make();
        $entry->collection($collection)->blueprint($blueprint->handle())->locale($site->handle())->published(false);

        if ($collection->dated()) {
            $entry->date(self::date($blueprint, $values));
        }

        $entry->data($values);

        // Like the CP's resolveSlug(): a closure, so an auto-generated title sees the data.
        $entry->slug(match (true) {
            is_string($stored['slug'] ?? null) => $stored['slug'],
            $blueprint->hasField('slug') => fn (Entry $entry): string => $entry->autoGeneratedTitle(),
            default => null,
        });

        $tree = $collection->structure()?->in($site->handle());

        if ($tree instanceof CollectionTree && $parent !== null && ! $tree->find($parent)) {
            throw ValidationException::withMessages(['parent' => "No page with id [{$parent}] in this collection's tree."]);
        }

        // Without a parent the CP appends to the end of the top level. Orderable
        // (one level deep) collections are appended by Entry::save() itself.
        if ($tree instanceof CollectionTree && ! $collection->orderable()) {
            $appendTo = $parent !== null && $tree->find($parent)?->isRoot() ? null : $parent;
            $entry->afterSave(fn (Entry $entry) => $tree->appendTo($appendTo, $entry)->save());
        }

        self::assertUniqueUri($entry, $tree instanceof CollectionTree ? $tree : null, $parent);

        $saved = $entry->updateLastModified($user)->save();

        // What Entry::store() does, except that its revision result would hide a cancelled entry save.
        if ($saved && $entry->revisionsEnabled()) {
            $saved = $entry->makeRevision()->user($user)->save();
        }

        NotSaved::unless($saved);

        return $entry;
    }

    /**
     * Never changes the published state. With revisions on, a published entry
     * gets a working copy like in the CP.
     *
     * @param  array<array-key, mixed>  $changes
     */
    public static function updateEntry(User $user, Entry $entry, array $changes): Entry
    {
        $entry = $entry->fromWorkingCopy();
        $collection = $entry->collection();
        $blueprint = $entry->blueprint();
        $fields = $blueprint->fields();
        $handles = DataPatch::handles($changes);
        self::assertKnown($fields, $handles, self::ENTRY_ATTRIBUTES);

        // The values the CP edit form starts from.
        $current = [...self::values($entry), 'slug' => $entry->slug()];

        if ($collection->dated()) {
            $current['date'] = mb_substr($entry->date()->setTimezone(config('app.timezone'))->toDateTimeString(), 0, 19);
        }

        $patched = self::patch($fields, $current, $changes, $handles);
        $merged = [...$current, ...AgentForm::toStored($fields, $patched, $current)];
        self::assertLocalizable($entry, $fields, Arr::only($merged, $handles), $current);
        self::assertReadOnlyUnchanged($fields, Arr::only($merged, $handles), $current, self::lockedHandles($collection, $blueprint));
        $preProcessed = self::preProcess($fields, $merged);

        self::validate($fields, $merged, $patched, fn () => $preProcessed->validator()
            ->withRules(Entries::updateRules($collection, $entry))
            ->withReplacements(['id' => $entry->id(), 'collection' => $collection->handle(), 'site' => $entry->locale()])
            ->validate());

        $values = self::ownValues($entry, self::written($fields, $preProcessed, $merged, $current, $handles), $current);
        $before = self::state($entry);

        if ($values->has('slug')) {
            $entry->slug($values->pull('slug'));
        }

        if ($values->has('date')) {
            $entry->date(self::date($blueprint, $values));
        }

        $entry->merge($values->all());

        // Nothing to store: a save would still rewrite the file and fire the save events.
        if (self::state($entry) === $before) {
            return $entry;
        }

        $tree = $collection->structure()?->in($entry->locale());
        self::assertUniqueUri($entry, $tree instanceof CollectionTree ? $tree : null, $entry->parent()?->id());

        if ($entry->revisionsEnabled() && $entry->published()) {
            NotSaved::unless($entry->makeWorkingCopy()->user($user)->save());

            return $entry->fromWorkingCopy();
        }

        NotSaved::unless($entry->updateLastModified($user)->save());

        return $entry;
    }

    /**
     * @param  array<array-key, mixed>  $changes
     */
    public static function updateGlobal(Variables $variables, array $changes): Variables
    {
        $fields = $variables->blueprint()->fields();
        $handles = DataPatch::handles($changes);
        self::assertKnown($fields, $handles, []);

        $current = self::values($variables);
        $patched = self::patch($fields, $current, $changes, $handles);
        $merged = [...$current, ...AgentForm::toStored($fields, $patched, $current)];
        self::assertLocalizable($variables, $fields, Arr::only($merged, $handles), $current);
        self::assertReadOnlyUnchanged($fields, Arr::only($merged, $handles), $current, []);
        $preProcessed = self::preProcess($fields, $merged);
        self::validate($fields, $merged, $patched, fn () => $preProcessed->validate());

        $before = self::state($variables);
        $variables->merge(self::ownValues($variables, self::written($fields, $preProcessed, $merged, $current, $handles), $current)->all());

        if (self::state($variables) !== $before) {
            NotSaved::unless($variables->save() !== false);
        }

        return $variables;
    }

    /**
     * Mirrors the CP's AssetsController::update(): blueprint data such as alt text.
     *
     * @param  array<array-key, mixed>  $changes
     */
    public static function updateAsset(Asset $asset, array $changes): Asset
    {
        $fields = $asset->blueprint()->fields();
        $handles = DataPatch::handles($changes);
        self::assertKnown($fields, $handles, []);

        $current = Arr::removeNullValues($asset->data()->all());
        $patched = self::patch($fields, $current, $changes, $handles);
        $merged = [...$current, ...AgentForm::toStored($fields, $patched, $current)];
        self::assertReadOnlyUnchanged($fields, Arr::only($merged, $handles), $current, []);
        $preProcessed = self::preProcess($fields, $merged);
        self::validate($fields, $merged, $patched, fn () => $preProcessed->validate());

        $before = self::state($asset);

        foreach (self::written($fields, $preProcessed, $merged, $current, $handles) as $handle => $value) {
            $asset->set($handle, $value);
        }

        if (self::state($asset) !== $before) {
            NotSaved::unless($asset->save());
        }

        return $asset;
    }

    /**
     * The stored-form data of one navigation node: $agent replaces the node's data,
     * parts equal to what is stored stay byte-identical.
     *
     * @param  array<array-key, mixed>  $agent
     * @param  array<array-key, mixed>  $current
     * @return array<array-key, mixed>
     */
    public static function branchData(Fields $fields, array $agent, array $current): array
    {
        $handles = array_keys($agent);
        self::assertKnown($fields, $handles, []);

        $merged = AgentForm::toStored($fields, $agent, $current);
        self::assertReadOnlyUnchanged($fields, $merged, $current, []);
        $preProcessed = self::preProcess($fields, $merged);
        self::validate($fields, $merged, $agent, fn () => $preProcessed->validate());

        return Arr::removeNullValues(self::written($fields, $preProcessed, $merged, $current, $handles)->all());
    }

    /**
     * Validated stored-form blueprint data for an asset that is about to be uploaded,
     * so a failure stops the upload before any file is written.
     *
     * @param  array<array-key, mixed>  $data
     * @return array<array-key, mixed>
     */
    public static function newAssetData(Blueprint $blueprint, array $data): array
    {
        $fields = $blueprint->fields();
        self::assertKnown($fields, array_keys($data), []);

        $stored = AgentForm::toStored($fields, $data, []);
        self::assertReadOnlyUnchanged($fields, $stored, [], []);
        $preProcessed = self::preProcess($fields, $stored);
        self::validate($fields, $stored, $data, fn () => $preProcessed->validate());

        return Arr::removeNullValues(self::processed($preProcessed, $stored)->only(array_keys($data))->all());
    }

    /**
     * Mirrors the CP's TermsController::store(). Terms have no drafts in Statamic.
     *
     * @param  array<array-key, mixed>  $data
     */
    public static function createTerm(User $user, Taxonomy $taxonomy, Blueprint $blueprint, Site $site, array $data): LocalizedTerm
    {
        $fields = $blueprint->fields();
        self::assertKnown($fields, array_keys($data), self::TERM_ATTRIBUTES);

        $stored = AgentForm::toStored($fields, $data, []);
        self::assertReadOnlyUnchanged($fields, $stored, [], []);

        // The CP's slug field fills itself from the title in the browser.
        if (! isset($stored['slug']) && is_string($stored['title'] ?? null)) {
            $stored['slug'] = Str::slug($stored['title'], '-', $site->lang());
        }

        $preProcessed = self::preProcess($fields, $stored);

        self::validate($fields, $stored, $data, fn () => $preProcessed->validator()
            ->withRules(['title' => 'required', 'slug' => ['required', new Slug, new UniqueTermValue(taxonomy: $taxonomy->handle(), site: $site->handle())]])
            ->withReplacements(['taxonomy' => $taxonomy->handle(), 'site' => $site->handle()])
            ->validate());

        $values = self::processed($preProcessed, $stored)->except(['slug', 'blueprint'])->all();
        $slug = (string) $stored['slug'];

        /** @var Term $term */
        $term = Terms::make();
        $term->taxonomy($taxonomy)->blueprint($blueprint->handle());
        $localized = $term->in($site->handle());
        $defaultSite = $taxonomy->sites()->first();

        // Like the CP: a term created in another site needs its default-site version too.
        if ($site->handle() !== $defaultSite) {
            $term->in($defaultSite)->data($values)->slug($slug);
        }

        $localized->data($values)->slug($slug);

        NotSaved::unless($localized->updateLastModified($user)->save());

        return $localized;
    }

    /**
     * Mirrors the CP's TermsController::update(). A slug change renames the term.
     *
     * @param  array<array-key, mixed>  $changes
     */
    public static function updateTerm(User $user, LocalizedTerm $term, array $changes): LocalizedTerm
    {
        $term->term()->syncOriginal();
        $fields = $term->blueprint()->fields();
        $handles = DataPatch::handles($changes);
        self::assertKnown($fields, $handles, self::TERM_ATTRIBUTES);

        $current = [...self::values($term), 'slug' => $term->slug()];
        $patched = self::patch($fields, $current, $changes, $handles);
        $merged = [...$current, ...AgentForm::toStored($fields, $patched, $current)];
        self::assertLocalizable($term, $fields, Arr::only($merged, $handles), $current);
        self::assertReadOnlyUnchanged($fields, Arr::only($merged, $handles), $current, []);
        $preProcessed = self::preProcess($fields, $merged);
        $taxonomy = $term->taxonomyHandle();
        $site = $term->locale();

        self::validate($fields, $merged, $patched, fn () => $preProcessed->validator()
            ->withRules(['title' => 'required', 'slug' => ['required', new Slug, new UniqueTermValue(taxonomy: $taxonomy, except: $term->id(), site: $site)]])
            ->withReplacements(['id' => $term->id(), 'taxonomy' => $taxonomy, 'site' => $site])
            ->validate());

        $values = self::ownValues($term, self::written($fields, $preProcessed, $merged, $current, $handles), $current);
        $before = self::state($term);

        if ($values->has('slug')) {
            $term->slug($values->pull('slug'));
        }

        $term->merge($values->all());

        if (self::state($term) === $before) {
            return $term;
        }

        NotSaved::unless($term->updateLastModified($user)->save());

        return $term;
    }

    /**
     * The stored field values an entry or global set resolves to: a localization's
     * own values over those of its origins. Like the CP's edit form, without the
     * values a collection injects.
     *
     * @return array<array-key, mixed>
     */
    public static function values(Entry|Variables|LocalizedTerm $item): array
    {
        $values = [];

        // A term's origin() is its default-site version, also for the default site itself.
        for ($target = $item; ; $target = $target->origin()) {
            $data = $target->data()->all();
            // A localization's null overrides its origin's value; a root's null is just empty.
            $values = [...($target->isRoot() ? Arr::removeNullValues($data) : $data), ...$values];

            if ($target->isRoot()) {
                return Arr::removeNullValues($values);
            }
        }
    }

    /**
     * A localization owns only its localizable fields; the others belong to the
     * origin, as in the CP, where they are read-only in a localization.
     *
     * @param  array<array-key, mixed>  $new
     * @param  array<array-key, mixed>  $old
     */
    private static function assertLocalizable(Entry|Variables|LocalizedTerm $item, Fields $fields, array $new, array $old): void
    {
        if ($item->isRoot()) {
            return;
        }

        $origin = $item->origin();

        $errors = [];

        foreach ($new as $handle => $value) {
            $field = $fields->get($handle);

            // Every localization has its own slug.
            if ($handle !== 'slug' && $field !== null && ! $field->isLocalizable() && $value !== ($old[$handle] ?? null)) {
                $errors[$handle] = [$origin instanceof Entry
                    ? "Not localizable. Change it on the origin entry [{$origin->id()}]."
                    : "Not localizable. Change it in the site [{$origin->locale()}]."];
            }
        }

        if ($errors !== []) {
            throw ValidationException::withMessages($errors);
        }
    }

    /**
     * The touched fields in agent form, with the changes applied.
     *
     * @param  array<array-key, mixed>  $current
     * @param  array<array-key, mixed>  $changes
     * @param  list<string>  $handles
     * @return array<array-key, mixed>
     */
    private static function patch(Fields $fields, array $current, array $changes, array $handles): array
    {
        return DataPatch::apply(AgentForm::fromStored($fields, Arr::only($current, $handles)), $changes);
    }

    /**
     * Runs the CP's validation, plus the check for numbers preProcess() would cast
     * with loss, and keys the errors by the paths the client writes.
     *
     * @param  array<array-key, mixed>  $stored  the values to validate, in stored form
     * @param  array<array-key, mixed>  $agent  the fields the client sent, in agent form
     * @param  Closure(): mixed  $validate
     */
    private static function validate(Fields $fields, array $stored, array $agent, Closure $validate): void
    {
        try {
            $lossy = AgentForm::lossyNumbers($fields, Arr::only($stored, array_keys($agent)));

            if ($lossy !== []) {
                throw ValidationException::withMessages($lossy);
            }

            $validate();
        } catch (ValidationException $e) {
            $handles = array_map(fn (int|string $path): string => explode('.', (string) $path)[0], array_keys($e->errors()));
            $agent = [...AgentForm::fromStored($fields, Arr::only(Arr::except($stored, array_keys($agent)), $handles)), ...$agent];
            $errors = [];

            foreach ($e->errors() as $path => $messages) {
                $errors[AgentForm::agentPath($fields, (string) $path, $stored, $agent)] = $messages;
            }

            throw ValidationException::withMessages($errors);
        }
    }

    /**
     * The processed values of the touched fields. Only these are written, and
     * within them every part the change left alone is swapped back for its stored
     * original, because processing normalises it (e.g. adds `enabled: true` to sets).
     *
     * @param  array<array-key, mixed>  $merged
     * @param  array<array-key, mixed>  $current
     * @param  list<string>  $handles
     * @return Values<array-key, mixed>
     */
    private static function written(Fields $fields, Fields $preProcessed, array $merged, array $current, array $handles): Values
    {
        $before = self::processed(self::preProcess($fields, $current), $current);

        return self::processed($preProcessed, $merged)->only($handles)->map(
            fn (mixed $value, int|string $handle): mixed => array_key_exists($handle, $current)
                ? AgentForm::keepUnchanged($value, $before->get($handle), $current[$handle])
                : $value,
        );
    }

    /**
     * What a save would store of an item, to tell whether there is anything to save.
     * A root's nulls are not stored; a localization's override its origin.
     */
    private static function state(Entry|Variables|LocalizedTerm|Asset $item): string
    {
        $data = $item->data()->all();
        $root = $item instanceof Asset || $item->isRoot();

        return (string) json_encode([
            $root ? Arr::removeNullValues($data) : $data,
            $item instanceof Entry || $item instanceof LocalizedTerm ? $item->slug() : null,
            $item instanceof Entry && $item->hasDate() ? $item->date()->format('Y-m-d H:i:s') : null,
        ]);
    }

    /**
     * In a localization, the values it sets itself: a value it inherits and the client
     * sent back unchanged stays inherited, so later changes of the origin still show.
     *
     * @param  Values<array-key, mixed>  $values
     * @param  array<array-key, mixed>  $current
     * @return Values<array-key, mixed>
     */
    private static function ownValues(Entry|Variables|LocalizedTerm $item, Values $values, array $current): Values
    {
        if ($item->isRoot()) {
            return $values;
        }

        $own = $item->data();

        return $values->reject(fn (mixed $value, int|string $handle): bool => ! $own->has($handle) && $value === ($current[$handle] ?? null));
    }

    /**
     * @param  array<array-key, mixed>  $values  stored form; a null clears the field
     */
    private static function preProcess(Fields $fields, array $values): Fields
    {
        $preProcessed = $fields->addValues(self::withNowDefaults($fields, $values))->preProcess();

        // Field::preProcess() puts the default in place of null, also nested, so validation would see the default.
        foreach ($values as $handle => $value) {
            $field = $preProcessed->get($handle);
            $field?->setValue(AgentForm::keepInputKeys($field->value(), $value, nullsOnly: true));
        }

        return $preProcessed;
    }

    /**
     * @param  array<array-key, mixed>  $input  the stored-form values that were preprocessed
     * @return Values<array-key, mixed>
     */
    private static function processed(Fields $preProcessed, array $input): Values
    {
        return $preProcessed->process()->values()->map(
            fn (mixed $value, int|string $handle): mixed => array_key_exists($handle, $input) ? AgentForm::keepInputKeys($value, $input[$handle]) : $value,
        );
    }

    /**
     * The CP's date picker turns a `now` default into the current time before it
     * submits; Statamic's date validation rejects the literal "now".
     *
     * @param  array<array-key, mixed>  $values
     * @return array<array-key, mixed>
     */
    private static function withNowDefaults(Fields $fields, array $values): array
    {
        foreach ($fields->all() as $handle => $field) {
            if ($field->type() === 'date' && ! array_key_exists($handle, $values) && $field->defaultValue() === 'now') {
                $values[$handle] = now()->toDateTimeString();
            }
        }

        return $values;
    }

    /**
     * @param  list<int|string>  $handles
     * @param  list<string>  $attributes  handles Statamic keeps next to the fields
     */
    private static function assertKnown(Fields $fields, array $handles, array $attributes): void
    {
        $errors = [];

        foreach ($handles as $handle) {
            if (in_array($handle, $attributes, true)) {
                $errors[$handle] = [$handle === 'published'
                    ? 'Not writable through data. Use publish_entry or unpublish_entry.'
                    : 'Statamic manages this attribute; it cannot be written.'];
            } elseif ($fields->get($handle) === null) {
                $errors[$handle] = ["Unknown field [{$handle}]. Call get_blueprint for this blueprint's fields."];
            }
        }

        if ($errors !== []) {
            throw ValidationException::withMessages($errors);
        }
    }

    /**
     * Read-only fields may be sent back unchanged, at any depth, but not changed.
     *
     * @param  array<array-key, mixed>  $new
     * @param  array<array-key, mixed>  $old
     * @param  list<string>  $locked
     */
    private static function assertReadOnlyUnchanged(Fields $fields, array $new, array $old, array $locked): void
    {
        $paths = AgentForm::readOnlyChanges($fields, $new, $old, $locked);

        if ($paths !== []) {
            throw ValidationException::withMessages(array_fill_keys($paths, ['This field is read-only.']));
        }
    }

    /**
     * Fields the CP never takes from this editor's submitted values.
     *
     * @return list<string>
     */
    private static function lockedHandles(Collection $collection, Blueprint $blueprint): array
    {
        return [
            ...($collection->autoGeneratesTitles() ? ['title'] : []),
            ...(self::authorLocked($collection, $blueprint) ? ['author'] : []),
        ];
    }

    private static function authorLocked(Collection $collection, Blueprint $blueprint): bool
    {
        return Gate::denies('edit-other-authors-entries', [EntryContract::class, $collection, $blueprint]);
    }

    /**
     * @param  Values<array-key, mixed>  $values
     */
    private static function date(Blueprint $blueprint, Values $values): mixed
    {
        return $blueprint->field('date')?->fieldtype()->augment($values->pull('date'));
    }

    /**
     * Mirrors EntriesController::validateUniqueUri(): two entries may not share a URL.
     * A new structured entry isn't in the tree yet, so its URI is built under the parent.
     */
    private static function assertUniqueUri(Entry $entry, ?CollectionTree $tree, ?string $parent): void
    {
        if (! $route = $entry->route()) {
            return;
        }

        if ($tree === null) {
            $uri = app(UrlBuilder::class)->content($entry)->merge(['id' => $entry->id() ?? Stache::generateId()])->build($route);
        } else {
            $parentPage = $parent !== null ? $tree->find($parent) : null;
            $parentPage = $parentPage?->isRoot() ? null : $parentPage;

            $uri = app(UrlBuilder::class)->content($entry)->merge([
                'parent_uri' => $parentPage?->uri(),
                'slug' => $entry->slug(),
                'depth' => $parentPage ? $parentPage->depth() + 1 : 1,
                'is_root' => false,
            ])->build($route);
        }

        $existing = Entries::findByUri($uri, $entry->locale());

        if ($existing instanceof Entry && $existing->id() !== $entry->id()) {
            throw ValidationException::withMessages(['slug' => __('statamic::validation.unique_uri')]);
        }
    }
}
